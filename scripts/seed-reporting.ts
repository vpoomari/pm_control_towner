function slug(n: string): string {
  return n.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

async function main() {
  console.log("◈ Reporting Center catalog seed…");
  let count = 0;
  for (const cat of CATALOG) {
    for (const r of cat.reports) {
      const code = `RPT-${cat.category.slice(0, 3)}-${slug(r.name).slice(0, 40)}`.toUpperCase();
      const payload = {
        code, name: r.name,
        description: `${r.name} — ${cat.category.toLowerCase()} report for ${cat.audience}. Computed from live ${r.source ?? cat.source} data.`,
        category: cat.category, audience: cat.audience,
        purpose: `Supports ${cat.audience} decision-making with ${(r.kpis ?? []).slice(0, 3).join(", ") || "operational"} metrics.`,
        kpis: JSON.stringify(r.kpis ?? []), charts: JSON.stringify(r.charts ?? []), tables: JSON.stringify(r.tables ?? ["summaryTable"]),
        filters: JSON.stringify(["portfolio", "project", "period", "rag"]),
        dataSource: r.source ?? cat.source, frequency: r.freq ?? cat.freq,
        ragLogic: cat.category === "EXECUTIVE" || cat.category === "PMO" ? "health: green>=80, amber>=60, red<60" : null,
        status: "PUBLISHED",
      };
      const existing = await db.reportingTemplate.findUnique({ where: { code } });
      if (existing) await db.reportingTemplate.update({ where: { code }, data: payload });
      else await db.reportingTemplate.create({ data: payload });
      count += 1;
    }
  }
  const total = await db.reportingTemplate.count();
  console.log(`  ✓ ${count} templates ensured — catalog total: ${total}`);
  await db.$disconnect();
}
main().catch((e) => { console.error("Seed failed:", e.message); process.exit(1); });
