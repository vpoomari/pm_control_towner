# PM CONTROL TOWER — First-run deploy (deployment pack).
# Prepares the application folder so the app can start:
#   1. creates .env with strong random secrets (only if missing — never overwrites)
#   2. creates runtime folders (db, logs, run, backups)
#   3. optionally re-initialises an EMPTY database with the bundled schema (-Fresh)
# Usage:
#   deploy.cmd                 normal first-run (keeps bundled db\custom.db data)
#   deploy.cmd -Fresh          start from an EMPTY database (requires internet for
#                              the Prisma engine download on first run)

param(
  [switch]$Fresh
)

. (Join-Path $PSScriptRoot "common.ps1")

Write-Step "Deploy / first-run preparation — pack root: $PackRoot"

# --- 1. runtime folders ------------------------------------------------------
foreach ($d in @("db", "logs", "run", "backups")) {
  New-Item -ItemType Directory -Force -Path (Join-Path $PackRoot $d) | Out-Null
}

# --- 2. .env ------------------------------------------------------------------
$envFile = Join-Path $PackRoot ".env"
if (Test-Path $envFile) {
  Write-Warn2 ".env already exists — keeping it (delete it to regenerate)."
} else {
  function New-Secret { 
    $bytes = New-Object byte[] 32
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    ($bytes | ForEach-Object { $_.ToString("x2") }) -join ""
  }
  $dbFile = Join-Path $PackRoot "db\custom.db"
  $dbUrl = "file:" + ($dbFile -replace "\\", "/")
  $envContent = @"
# PM CONTROL TOWER — generated by deploy.cmd $(Get-Date -Format "yyyy-MM-dd HH:mm")
# Edit freely; restart the app afterwards.

# Database (absolute file URL)
DATABASE_URL=$dbUrl

# Security (randomly generated at install — rotate for production)
JWT_SECRET=$(New-Secret)
REALTIME_SECRET_KEY=$(New-Secret)
REALTIME_SECRET=$(New-Secret)

# Realtime gateway (optional mini service; the app runs without it)
REALTIME_URL=http://127.0.0.1:3003
REALTIME_PORT=3003

# HTTP server
PORT=3000
HOSTNAME=127.0.0.1
"@
  Set-Content $envFile $envContent -Encoding UTF8
  Write-Ok ".env generated with fresh random secrets."
}

# --- 3. optional fresh database ------------------------------------------------
if ($Fresh) {
  $dbFile = Join-Path $PackRoot "db\custom.db"
  if (Test-Path $dbFile) {
    Copy-Item $dbFile (Join-Path $PackRoot "backups") -Force -ErrorAction SilentlyContinue
    Remove-Item $dbFile -Force
    Write-Warn2 "Removed existing db\custom.db (a copy was left in backups\)."
  }
  Write-Step "Initialising empty database with prisma db push (needs internet on first run)..."
  $schema = Join-Path $PackRoot "prisma\schema.prisma"
  Push-Location $PackRoot
  try {
    $env:DATABASE_URL = "file:" + ($dbFile -replace "\\", "/")
    npx --yes prisma@6 db push --schema "$schema" --skip-generate
    if ($LASTEXITCODE -ne 0) { throw "prisma db push failed with exit code $LASTEXITCODE" }
    Write-Ok "Empty database created. Sign up on first launch to create the admin account."
  } finally {
    Pop-Location
  }
}

# --- 4. sanity checks -----------------------------------------------------------
$checks = @(
  @{ p = "app\server.js";              what = "bundled server" },
  @{ p = "prisma\schema.prisma";       what = "database schema" },
  @{ p = ".env";                       what = "environment config" }
)
$missing = @()
foreach ($c in $checks) {
  if (Test-Path (Join-Path $PackRoot $c.p)) { Write-Ok "$($c.what) present" }
  else { $missing += $c.what; Write-Warn2 "MISSING: $($c.what) ($($c.p))" }
}
if ($missing) { throw "Pack incomplete: $($missing -join ', '). Re-extract the full deployment package." }

Write-Ok "Deployment ready. Starting the app..."
Start-App
Write-Host ""
Write-Host "  Open the app:  http://localhost:$Port" -ForegroundColor White
Write-Host "  First sign-in: use the seeded accounts from docs\DEPLOYMENT-GUIDE.md (section 6)" -ForegroundColor Gray
Write-Host "  Stop:          stop.cmd      Backup:  backup.cmd" -ForegroundColor Gray
